# Python Assignment Operators

a = 10
print("Initial value of a =", a)

# Addition Assignment
a += 5
print("a += 5 :", a)

# Subtraction Assignment
a -= 3
print("a -= 3 :", a)

# Multiplication Assignment
a *= 2
print("a *= 2 :", a)

# Division Assignment
a /= 4
print("a /= 4 :", a)

# Modulus Assignment
a %= 3
print("a %= 3 :", a)

# Exponent Assignment
a = 5
a **= 2
print("a **= 2 :", a)

# Floor Division Assignment
a = 10
a //= 3
print("a //= 3 :", a)

# Bitwise AND Assignment
a = 10
a &= 6
print("a &= 6 :", a)

# Bitwise OR Assignment
a = 10
a |= 6
print("a |= 6 :", a)

# Bitwise XOR Assignment
a = 10
a ^= 6
print("a ^= 6 :", a)

# Left Shift Assignment
a = 10
a <<= 1
print("a <<= 1 :", a)

# Right Shift Assignment
a = 10
a >>= 1
print("a >>= 1 :", a)